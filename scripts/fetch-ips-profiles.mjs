/**
 * scripts/fetch-ips-profiles.mjs
 *
 * Phase 44 Plan 44-01, IPS-01.
 *
 * Fetches the HL7 IPS IG package (hl7.fhir.uv.ips@2.0.0) via
 * fhir-package-loader@^2.2.4, extracts StructureDefinition resources,
 * trims them via the shared scripts/lib/trim-profile.mjs, and writes:
 *   - src/quality/profiles/ips/<type>-<slug>.json (one per SD)
 *   - src/quality/profiles/ips/index.ts (URL-keyed IPS_REGISTRY)
 *   - src/quality/profiles/ips/ATTRIBUTION.md (per-package metadata)
 *
 * Mirrors scripts/fetch-mii-profiles.mjs but ships only the IPS package
 * (D-02 — single-package fetcher; transitive deps are NOT extracted —
 * walker only reads top-level Composition-uv-ips per RESEARCH §2).
 *
 * Failure mode: warn-and-continue (CONTEXT D-13 idiom). Top-level catch
 * exits 0; defensive empty-fetch early-return preserves committed JSON
 * (44-RESEARCH §6 Pitfall 8). The `|| true` escape in the prepare hook
 * is belt-and-braces.
 *
 * License: hl7.fhir.uv.ips ships under CC0-1.0 (public domain dedication).
 * Attribution is good-practice; LICENSE root section + ATTRIBUTION.md.
 */

import { defaultPackageLoader, LoadStatus } from 'fhir-package-loader';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { trim } from './lib/trim-profile.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(__dirname, '..', 'src', 'quality', 'profiles', 'ips');

// Live-probed 2026-04-30 in 44-RESEARCH.md §2: dist-tags.latest = '2.0.0'.
const IPS_PACKAGES = [
  ['hl7.fhir.uv.ips', '2.0.0'],
];

const PRE_GA_PATTERN = /-(alpha|beta|rc|ballot|draft)/i;

// Canonical URL for ATTRIBUTION.md (matches package.json `canonical` field).
const CANONICAL_URLS = {
  'hl7.fhir.uv.ips': 'http://hl7.org/fhir/uv/ips',
};

// Per-package license (CC0-1.0 — different from MII fetcher's CC-BY-4.0).
const PACKAGE_LICENSES = {
  'hl7.fhir.uv.ips': 'CC0-1.0',
};

function slugify(s) {
  return String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

async function main() {
  await fs.mkdir(OUT_DIR, { recursive: true });

  const log = (level, msg) => {
    if (level === 'error') console.warn(`[${level}] ${msg}`);
    else console.log(`[${level}] ${msg}`);
  };
  const loader = await defaultPackageLoader({ log });

  const fetchedOn = new Date().toISOString();
  const registryByUrl = new Map();
  const attributionSections = [];

  for (const [name, version] of IPS_PACKAGES) {
    if (PRE_GA_PATTERN.test(version)) {
      console.info(`[info] bundling pre-GA version: ${name}@${version}`);
    }

    const status = await loader.loadPackage(name, version).catch((err) => {
      console.warn(`[warn] ${name}@${version} — fetch failed: ${err?.message ?? err}`);
      return LoadStatus.FAILED;
    });

    attributionSections.push(
      `## ${name}\n\n` +
      `- **Canonical URL:** ${CANONICAL_URLS[name] ?? '(unknown)'}\n` +
      `- **Bundled version:** ${version}\n` +
      `- **License:** ${PACKAGE_LICENSES[name] ?? '(unknown)'}\n` +
      `- **Source:** https://packages.fhir.org/${name}\n` +
      `- **Fetched on:** ${fetchedOn}\n`,
    );

    if (status !== LoadStatus.LOADED) {
      console.warn(`[warn] ${name}@${version} — status ${status}; skipping, relying on committed JSON`);
      continue;
    }

    // fhir-package-loader v2 API: findResourceJSONs(key, { type, scope, ... }).
    const sds = loader.findResourceJSONs('*', {
      type: ['StructureDefinition'],
      scope: name,
    }) ?? [];

    for (const sd of sds) {
      const slug = slugify(sd.name ?? sd.id ?? sd.url?.split('/').pop() ?? 'unknown');
      const typeSlug = String(sd.type ?? 'Unknown').replace(/[^A-Za-z0-9]+/g, '');
      const filename = `${typeSlug}-${slug}.json`;
      await fs.writeFile(
        path.join(OUT_DIR, filename),
        JSON.stringify(trim(sd), null, 2) + '\n',
      );
      registryByUrl.set(
        sd.url,
        '  ' + JSON.stringify(sd.url) + ": () => import('./" + filename + "') as unknown as Promise<{ default: StructureDefinition }>,",
      );
    }
    console.log(`[ok] ${name}@${version} — wrote ${sds.length} StructureDefinition(s)`);
  }

  // Defensive empty-fetch early-return (RESEARCH §6 Pitfall 8 — mirrors MII fetcher lines 184-201).
  const registryLines = [...registryByUrl.values()];
  if (registryLines.length === 0) {
    console.warn(
      '[warn] no IPS StructureDefinitions fetched (offline or all failed); ' +
      'preserving committed src/quality/profiles/ips/index.ts + ATTRIBUTION.md',
    );
    return;
  }

  // Regenerate index.ts (Phase 36 lazy-thunks shape — exports IPS_REGISTRY,
  // NOT REGISTRY, so consumers can import both registries unambiguously).
  const indexContent =
    "// GENERATED by scripts/fetch-ips-profiles.mjs — DO NOT EDIT BY HAND.\n" +
    "// Regenerated on npm install via the 'prepare' lifecycle hook.\n" +
    "// Phase 44: per-URL lazy-load thunks for HL7 IPS profiles.\n" +
    "import type { StructureDefinition } from '@medplum/fhirtypes';\n\n" +
    "type LazyProfile = () => Promise<{ default: StructureDefinition }>;\n\n" +
    "export const IPS_REGISTRY: Record<string, LazyProfile> = {\n" +
    registryLines.join("\n") +
    "\n};\n";
  await fs.writeFile(path.join(OUT_DIR, 'index.ts'), indexContent);

  // Regenerate ATTRIBUTION.md.
  const attributionContent =
    `# Bundled HL7 IPS StructureDefinition Profiles — Attribution\n\n` +
    `The HL7 IPS package (hl7.fhir.uv.ips) ships under the **CC0-1.0** public\n` +
    `domain dedication. No legal attribution is required, but we list the\n` +
    `bundled version + canonical URL here as good practice and to keep update\n` +
    `provenance traceable. The trimmed JSONs in this directory are derivatives\n` +
    `of the upstream package below.\n\n` +
    `The FHIR Exploder source code itself remains MIT-licensed — see the root\n` +
    `LICENSE file for details.\n\n` +
    attributionSections.join('\n');
  await fs.writeFile(path.join(OUT_DIR, 'ATTRIBUTION.md'), attributionContent);
}

main().catch((err) => {
  console.warn(`[warn] fetch-ips-profiles failed globally: ${err?.message ?? err}`);
  process.exit(0);
});
